-- 공고에 주관기관 칸을 만든다.
--
-- 같은 공고가 두 줄로 들어와 있다 (실측 2026-11-05: 600건 중 29묶음 58줄).
-- 수집기가 모은 줄과 홈페이지가 스스로 모은 줄이 겹친다. LGD Dream Play 는
-- 기업마당 줄과 K-Startup 줄이 따로 있고, 아침 정독 목록에는 K-Startup 줄이
-- 뜬다. 그래서 수집기가 뽑은 모집분야가 목록에 뜨는 줄로 가지 못한다.
--
-- 접으려면 같은 공고인지 가려야 하는데, **제목만으로는 못 가린다.**
-- 닮음만 보면 이런 것이 묶인다:
--     [경기] 하남시 2027년 유기질비료 지원사업 추가
--     [경기] 화성시 2027년 유기질비료 지원사업 추가   ← 다른 시, 다른 공고
-- 시 이름만 다르고 나머지가 같아서 점수가 높게 나온다. 이대로 접으면
-- 멀쩡한 공고가 사라진다.
--
-- 수집기의 중복 규칙(gonggo/dedupe)은 **기관명**으로 이것을 가른다.
-- 그 규칙을 홈페이지에서도 쓰려면 이 칸이 있어야 한다.
--
-- 비워 둘 수 있다. 예전에 들어온 줄과 홈페이지가 스스로 모은 줄은 비어 있고,
-- 비어 있으면 기관으로 가리지 않는다 — 빈칸을 '다른 기관' 으로 읽지 않는다.
alter table public.openchat_programs
  add column if not exists org_name text
    check (org_name is null or length(org_name) between 1 and 200);

comment on column public.openchat_programs.org_name is
  '주관기관. 같은 공고가 두 줄일 때 접을지 가리는 데 쓴다. 비면 기관으로 가리지 않는다.';
